import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = fileURLToPath(new URL("..", import.meta.url));
const distDir = join(projectRoot, "dist");
const swPath = join(distDir, "sw.js");

async function walk(dir) {
  const entries = await readdir(dir);
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry);
    const info = await stat(full);
    if (info.isDirectory()) {
      files.push(...(await walk(full)));
    } else {
      files.push(full);
    }
  }
  return files;
}

const files = await walk(distDir);
const assets = files
  .map((file) => "/" + relative(distDir, file).split(sep).join("/"))
  .filter((path) => path !== "/sw.js")
  .sort();

if (assets.length === 0) {
  throw new Error("No build output found in dist/. Run `vite build` first.");
}

const hash = createHash("sha256");
for (const asset of assets) {
  hash.update(asset);
  hash.update(await readFile(join(distDir, asset)));
}
const version = hash.digest("hex").slice(0, 12);

const template = `/* Generated by scripts/generate-sw.mjs — do not edit by hand. */
const VERSION = ${JSON.stringify(version)};
const SHELL_CACHE = \`vendor-pos-shell-\${VERSION}\`;
const RUNTIME_CACHE = "vendor-pos-runtime";

const SHELL_ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(SHELL_CACHE);
      await cache.addAll(SHELL_ASSETS.map((asset) => new Request(asset, { cache: "reload" })));
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => key.startsWith("vendor-pos-shell-") && key !== SHELL_CACHE)
          .map((key) => caches.delete(key)),
      );
      await self.clients.claim();
    })(),
  );
});

function isCacheable(request, response) {
  return (
    request.method === "GET" &&
    response &&
    response.status === 200 &&
    response.type === "basic"
  );
}

self.addEventListener("fetch", (event) => {
  const { request } = event;

  if (request.method !== "GET" || request.headers.has("range")) {
    return;
  }

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) {
    return;
  }

  if (request.mode === "navigate") {
    event.respondWith(
      (async () => {
        const cache = await caches.open(SHELL_CACHE);
        try {
          const response = await fetch(request);
          if (isCacheable(request, response)) {
            await cache.put("/index.html", response.clone());
          }
          return response;
        } catch {
          const cached = (await cache.match("/index.html")) || (await cache.match("/"));
          if (cached) return cached;
          throw new Error("Offline and no cached app shell available.");
        }
      })(),
    );
    return;
  }

  event.respondWith(
    (async () => {
      const cached = await caches.match(request);
      if (cached) return cached;

      try {
        const response = await fetch(request);
        if (isCacheable(request, response)) {
          const cache = await caches.open(RUNTIME_CACHE);
          await cache.put(request, response.clone());
        }
        return response;
      } catch (error) {
        const fallback = await caches.match(request, { ignoreSearch: true });
        if (fallback) return fallback;
        throw error;
      }
    })(),
  );
});
`;

await writeFile(swPath, template, "utf8");

const totalKb = (
  (await Promise.all(files.map(async (file) => (await stat(file)).size))).reduce(
    (sum, size) => sum + size,
    0,
  ) / 1024
).toFixed(1);

console.log(
  `Service worker generated: ${assets.length} precached files (${totalKb} KiB), version ${version}`,
);
